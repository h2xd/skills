/**
 * Prints what an agent needs to write a form file of one page type: the
 * signatures from the schema, the rules, and a short example.
 */

import { readFileSync } from "node:fs"
import { join } from "node:path"
import { HELPERS, PAGES, RULES, type PageType } from "./schema.ts"

const COMMON_RULES = [
  "Text fields accept `code`, **bold**, [link](url) and \\n. Never write HTML.",
  "An unknown field is an error. JSON keeps only the last of two equal keys, so never repeat a key.",
]

/** The type's example, cut to its first two items, one item per line. */
export function shortExample(type: PageType): string {
  const parsed: unknown = JSON.parse(readFileSync(join(import.meta.dirname, "types", type, "example.form.json"), "utf8"))
  if (typeof parsed !== "object" || parsed === null || !("items" in parsed) || !Array.isArray(parsed.items)) {
    throw new Error(`types/${type}/example.form.json has no items`)
  }
  const { items, ...head } = parsed
  const top = JSON.stringify(head).slice(0, -1)
  const lines = items.slice(0, 2).map((item: unknown) => ` ${JSON.stringify(item)}`)
  return `${top},"items":[\n${lines.join(",\n")}\n]}`
}

export function spec(type: PageType): string {
  return [
    PAGES[type].signature,
    ...HELPERS[type].map((helper) => helper.signature),
    "",
    "Rules:",
    ...[...RULES[type], ...COMMON_RULES].map((rule) => `- ${rule}`),
    "",
    "Example:",
    shortExample(type),
  ].join("\n")
}

/** spec.md: every type's spec, for the skill to read. */
export function specMarkdown(): string {
  const types = Object.keys(PAGES).filter((type): type is PageType => type in PAGES)
  const sections = types.map((type) => `## ${type}\n\n\`\`\`\n${spec(type)}\n\`\`\``)
  return [
    "# Page types",
    "",
    "Generated by `node scripts/to-page.ts spec --md`. Do not edit by hand.",
    "",
    sections.join("\n\n"),
    "",
  ].join("\n")
}
