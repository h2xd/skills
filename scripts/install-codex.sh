#!/bin/sh
# Installs the h2xd skills and agents for Codex.
#
#   curl -fsSL https://raw.githubusercontent.com/h2xd/skills/main/scripts/install-codex.sh | sh
#   sh scripts/install-codex.sh                  for you, in ~/.agents and ~/.codex
#   sh scripts/install-codex.sh --project DIR    for one repo, in DIR/.agents and DIR/.codex
#   options: --copy  copy instead of link   --force  replace what is in the way
#            --uninstall  remove what this script installed
#
# Skills land in .agents/skills/<name>, linked to this repo so a git pull
# updates them. Some skills read ../../templates and ../../agents by relative
# path, so those two folders are linked next to .agents/skills too. Each agent
# in agents/ becomes .codex/agents/<name>.toml, the format Codex reads.

set -eu

REPO=$(cd "$(dirname "$0")/.." 2>/dev/null && pwd || true)

# Piped from curl, $0 is the shell, not this file, so there is no repo next to
# it. Clone it, or update the clone from an earlier run, then run that copy.
if [ ! -f "$REPO/scripts/install-codex.sh" ] || [ ! -f "$REPO/.claude-plugin/plugin.json" ]; then
  command -v git >/dev/null 2>&1 || { echo "install-codex needs git to fetch the skills" >&2; exit 1; }
  CLONE=${H2XD_HOME:-$HOME/.h2xd-skills}
  if [ -d "$CLONE/.git" ]; then
    git -C "$CLONE" pull --quiet --ff-only
  else
    git clone --quiet https://github.com/h2xd/skills.git "$CLONE"
  fi
  exec sh "$CLONE/scripts/install-codex.sh" "$@"
fi
BASE=$HOME
MODE=link
FORCE=""
UNINSTALL=""
MARK="# Generated by h2xd scripts/install-codex.sh. Run it again to update."

while [ $# -gt 0 ]; do
  case "$1" in
    --project)
      [ $# -ge 2 ] || { echo "--project needs a directory" >&2; exit 2; }
      [ -d "$2" ] || { echo "--project: $2 is not a directory" >&2; exit 2; }
      BASE=$(cd "$2" && pwd)
      shift ;;
    --copy) MODE=copy ;;
    --force) FORCE=1 ;;
    --uninstall) UNINSTALL=1 ;;
    *) sed -n '4,8p' "$0" | sed 's/^# //' >&2; exit 2 ;;
  esac
  shift
done

SKILLS="$BASE/.agents/skills"
AGENTS="$BASE/.codex/agents"
installed=0 skipped=0 removed=0

# True when PATH is ours: a link into this repo, or a file we generated.
ours() {
  if [ -L "$1" ]; then
    case "$(readlink "$1")" in "$REPO"/*) return 0 ;; esac
    return 1
  fi
  [ -f "$1/.h2xd-install" ] && return 0
  [ -f "$1" ] && head -n 1 "$1" | grep -qF "$MARK"
}

# Puts SOURCE at TARGET, unless something that is not ours is in the way.
place() {
  source=$1 target=$2
  if [ -e "$target" ] || [ -L "$target" ]; then
    if ! ours "$target" && [ -z "$FORCE" ]; then
      echo "skip $target: something else is there. Use --force to replace it." >&2
      skipped=$((skipped + 1))
      return
    fi
    rm -rf "$target"
  fi
  if [ "$MODE" = copy ]; then
    cp -R "$source" "$target"
    echo "$MARK" > "$target/.h2xd-install"
  else
    ln -s "$source" "$target"
  fi
  installed=$((installed + 1))
}

remove() {
  if ours "$1"; then rm -rf "$1"; removed=$((removed + 1)); fi
}

# The frontmatter value of KEY in FILE, without surrounding quotes.
field() {
  awk -v key="$1" 'NR == 1 && /^---$/ { inside = 1; next }
    inside && /^---$/ { exit }
    inside && index($0, key ": ") == 1 { sub("^" key ": *", ""); sub(/^"/, ""); sub(/"$/, ""); print; exit }' "$2"
}

# Writes the Codex TOML for the agent in FILE to TARGET.
agent_toml() {
  file=$1 target=$2
  name=$(field name "$file")
  description=$(field description "$file" | sed 's/\\/\\\\/g; s/"/\\"/g')
  body=$(awk 'NR == 1 && /^---$/ { fm = 1; next } fm && /^---$/ { fm = 0; next } !fm' "$file")
  case "$body" in *"'''"*) echo "$file holds ''' and cannot become a TOML literal" >&2; exit 1 ;; esac
  {
    echo "$MARK"
    echo "name = \"$name\""
    echo "description = \"$description\""
    echo "developer_instructions = '''"
    printf '%s\n' "$body"
    echo "'''"
  } > "$target"
}

if [ -n "$UNINSTALL" ]; then
  for dir in "$REPO"/skills/*/; do remove "$SKILLS/$(basename "$dir")"; done
  remove "$BASE/.agents/templates"
  remove "$BASE/.agents/agents"
  for file in "$REPO"/agents/*.md; do remove "$AGENTS/$(field name "$file").toml"; done
  echo "removed $removed items from $BASE"
  exit 0
fi

mkdir -p "$SKILLS" "$AGENTS"
for dir in "$REPO"/skills/*/; do
  place "${dir%/}" "$SKILLS/$(basename "$dir")"
done
place "$REPO/templates" "$BASE/.agents/templates"
place "$REPO/agents" "$BASE/.agents/agents"

for file in "$REPO"/agents/*.md; do
  target="$AGENTS/$(field name "$file").toml"
  if [ -e "$target" ] && ! ours "$target" && [ -z "$FORCE" ]; then
    echo "skip $target: something else is there. Use --force to replace it." >&2
    skipped=$((skipped + 1))
    continue
  fi
  agent_toml "$file" "$target"
  installed=$((installed + 1))
done

echo "installed $installed items in $BASE, skipped $skipped"
echo "Restart Codex, then call a skill with \$<name>, such as \$plan-grill."
